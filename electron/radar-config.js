function pickRadarSettings(source = {}) {
  const out = {};
  if (!source || typeof source !== "object") return out;
  for (const key of RADAR_CONFIG_KEYS) {
    if (Object.prototype.hasOwnProperty.call(source, key)) {
      out[key] = source[key];
    }
  }
  return out;
}

/**
 * @param {object} settings full or partial settings
 * @param {{ name?: string }} [meta]
 * @returns {Buffer}
 */
function buildImxBuffer(settings, meta = {}) {
  const name = String(meta.name || "Radar Config")
    .trim()
    .slice(0, 80) || "Radar Config";
  const payload = {
    version: RADAR_CONFIG_VERSION,
    kind: RADAR_CONFIG_KIND,
    name,
    exportedAt: new Date().toISOString(),
    settings: pickRadarSettings(settings),
  };
  const b64 = Buffer.from(JSON.stringify(payload), "utf8").toString("base64");
  return Buffer.concat([IMX_MAGIC, Buffer.from(b64, "utf8")]);
}

/**
 * @param {Buffer|Uint8Array|string} input
 * @returns {{ ok: true, payload: object } | { ok: false, reason: string }}
 */
function parseImxBuffer(input) {
  let buf;
  try {
    if (Buffer.isBuffer(input)) buf = input;
    else if (input instanceof Uint8Array) buf = Buffer.from(input);
    else if (typeof input === "string") buf = Buffer.from(input, "binary");
    else return { ok: false, reason: "bad-input" };
  } catch {
    return { ok: false, reason: "bad-input" };
  }

  if (buf.length < 5) return { ok: false, reason: "bad-magic" };
  if (buf.subarray(0, 4).toString("ascii") !== "IMX1") {
    return { ok: false, reason: "bad-magic" };
  }

  let json;
  try {
    const b64 = buf.subarray(4).toString("utf8").replace(/\s+/g, "");
    json = JSON.parse(Buffer.from(b64, "base64").toString("utf8"));
  } catch {
    return { ok: false, reason: "bad-payload" };
  }

  if (
    !json ||
    typeof json !== "object" ||
    json.kind !== RADAR_CONFIG_KIND ||
    Number(json.version) !== RADAR_CONFIG_VERSION
  ) {
    return { ok: false, reason: "bad-schema" };
  }
  if (!json.settings || typeof json.settings !== "object") {
    return { ok: false, reason: "bad-settings" };
  }

  const name =
    String(json.name || "Radar Config")
      .trim()
      .slice(0, 80) || "Radar Config";

  return {
    ok: true,
    payload: {
      version: RADAR_CONFIG_VERSION,
      kind: RADAR_CONFIG_KIND,
      name,
      exportedAt: json.exportedAt ? String(json.exportedAt) : null,
      settings: pickRadarSettings(json.settings),
    },
  };
}

/**
 * Merge radar keys from pack into current settings object (does not write disk).
 * @returns {object} partial suitable for saveSettings / applySettings
 */
function applyRadarSettings(_current, packSettings) {
  return pickRadarSettings(packSettings || {});
}

function isImxPath(filePath) {
  return (
    typeof filePath === "string" &&
    filePath.length > 4 &&
    filePath.toLowerCase().endsWith(".imx")
  );
}

