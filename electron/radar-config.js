function templatePreview(settings = {}) {
  return {
    design: settings.mapDesign || "tactical",
    basemap: settings.basemap || "gateway-official",
    borderStyle: settings.borderStyle || "classic",
    borderColor: settings.borderColor || "#5ec8ff",
    borderGlow: Number(settings.borderGlow ?? 14),
    pinColor: settings.pinColor || "#5ef0ff",
    fovColor: settings.fovColor || "#b6ff4a",
    effect: settings.borderEffect || "none",
    sweep: Boolean(settings.showRadarSweep),
  };
}

function listRadarTemplates() {
  return RADAR_TEMPLATES.map((t) => ({
    id: t.id,
    name: t.name,
    description: t.description || "",
    preview: templatePreview(t.settings),
  }));
}

function getRadarTemplate(id) {
  const t = RADAR_TEMPLATES.find((x) => x.id === id);
  if (!t) return null;
  return {
    version: RADAR_CONFIG_VERSION,
    kind: RADAR_CONFIG_KIND,
    name: t.name,
    exportedAt: null,
    templateId: t.id,
    settings: pickRadarSettings(t.settings),
  };
}

